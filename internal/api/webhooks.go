func (a *API) webhookRoutes(mux *http.ServeMux, admin func(http.HandlerFunc) http.Handler) {
	mux.Handle("GET /api/v1/webhooks", admin(a.listWebhooks))
	mux.Handle("GET /api/v1/webhooks/events", admin(a.webhookEvents))
	mux.Handle("POST /api/v1/webhooks", admin(a.saveWebhook))
	mux.Handle("GET /api/v1/webhooks/{id}", admin(a.getWebhook))
	mux.Handle("PUT /api/v1/webhooks/{id}", admin(a.saveWebhook))
	mux.Handle("DELETE /api/v1/webhooks/{id}", admin(a.deleteWebhook))
	mux.Handle("POST /api/v1/webhooks/{id}/rotate-secret", admin(a.rotateWebhookSecret))
	mux.Handle("POST /api/v1/webhooks/{id}/test", admin(a.testWebhook))
	mux.Handle("GET /api/v1/webhooks/{id}/deliveries", admin(a.listWebhookDeliveries))
	mux.Handle("POST /api/v1/webhooks/{id}/deliveries/{deliveryId}/retry", admin(a.retryWebhookDelivery))
}

func (a *API) webhookEvents(w http.ResponseWriter, r *http.Request) {
	httpx.JSON(w, http.StatusOK, map[string]any{"events": webhook.Catalogue})
}

func (a *API) listWebhooks(w http.ResponseWriter, r *http.Request) {
	hooks, err := a.Store.ListWebhooks(r.Context())
	if err != nil {
		a.fail(w, err)
		return
	}
	httpx.JSON(w, http.StatusOK, map[string]any{"webhooks": nonNil(hooks)})
}

func (a *API) getWebhook(w http.ResponseWriter, r *http.Request) {
	hook, err := a.Store.WebhookByID(r.Context(), r.PathValue("id"))
	if err != nil {
		a.fail(w, err)
		return
	}
	httpx.JSON(w, http.StatusOK, hook)
}

// saveWebhook creates (POST) or updates (PUT) a webhook. The signing secret is
// generated by the server and returned once, on creation.
func (a *API) saveWebhook(w http.ResponseWriter, r *http.Request) {
	var req struct {
		Name    string   `json:"name"`
		URL     string   `json:"url"`
		Events  []string `json:"events"`
		Enabled *bool    `json:"enabled"`
	}
	if err := decode(r, &req); err != nil {
		httpx.Error(w, http.StatusBadRequest, "malformed request")
		return
	}
	req.Name, req.URL = strings.TrimSpace(req.Name), strings.TrimSpace(req.URL)
	var problems []string
	if req.Name == "" {
		problems = append(problems, "name is required")
	}
	if err := webhook.ValidateURL(req.URL); err != nil {
		problems = append(problems, err.Error())
	}
	if len(req.Events) == 0 {
		problems = append(problems, "choose at least one event")
	}
	seen := map[string]bool{}
	events := []string{}
	for _, e := range req.Events {
		if !webhook.Known(e) {
			problems = append(problems, "unknown event "+strconv.Quote(e))
			continue
		}
		if !seen[e] {
			seen[e] = true
			events = append(events, e)
		}
	}
	if len(problems) > 0 {
		httpx.JSON(w, http.StatusBadRequest, map[string]any{"error": strings.Join(problems, "; "), "problems": problems})
		return
	}
	enabled := req.Enabled == nil || *req.Enabled
	ctx := r.Context()
	id := r.PathValue("id")
	hook := &store.Webhook{ID: id, Name: req.Name, URL: req.URL, Events: events, Enabled: enabled}

	if id != "" {
		if !a.audit(w, r, "webhook.update", id, map[string]any{"name": hook.Name, "url": hook.URL, "events": events, "enabled": enabled}) {
			return
		}
		saved, err := a.Store.UpdateWebhook(ctx, hook)
		if err != nil {
			a.webhookSaveError(w, err)
			return
		}
		if !saved.Enabled {
			// A stale backlog must not be replayed when it is enabled again.
			if err := a.Store.FailPendingDeliveries(ctx, saved.ID, "not sent: the webhook was disabled"); err != nil {
				a.fail(w, err)
				return
			}
		}
		httpx.JSON(w, http.StatusOK, saved)
		return
	}

	secret := webhook.NewSecret()
	sealed, err := a.Box.Seal([]byte(secret))
	if err != nil {
		a.fail(w, err)
		return
	}
	hook.Secret = sealed
	if !a.audit(w, r, "webhook.create", hook.Name, map[string]any{"url": hook.URL, "events": events, "enabled": enabled}) {
		return
	}
	saved, err := a.Store.CreateWebhook(ctx, hook)
	if err != nil {
		a.webhookSaveError(w, err)
		return
	}
	httpx.JSON(w, http.StatusCreated, map[string]any{"webhook": saved, "secret": secret})
}

func (a *API) webhookSaveError(w http.ResponseWriter, err error) {
	if strings.Contains(err.Error(), "duplicate") {
		httpx.Error(w, http.StatusConflict, "a webhook with that name exists")
		return
	}
	a.fail(w, err)
}

func (a *API) deleteWebhook(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	if !a.audit(w, r, "webhook.delete", id, nil) {
		return
	}
	if err := a.Store.DeleteWebhook(r.Context(), id); err != nil {
		a.fail(w, err)
		return
	}
	w.WriteHeader(http.StatusNoContent)
}

func (a *API) rotateWebhookSecret(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	if _, err := a.Store.WebhookByID(r.Context(), id); err != nil {
		a.fail(w, err)
		return
	}
	secret := webhook.NewSecret()
	sealed, err := a.Box.Seal([]byte(secret))
	if err != nil {
		a.fail(w, err)
		return
	}
	if !a.audit(w, r, "webhook.rotate_secret", id, nil) {
		return
	}
	if err := a.Store.SetWebhookSecret(r.Context(), id, sealed); err != nil {
		a.fail(w, err)
		return
	}
	httpx.JSON(w, http.StatusOK, map[string]any{"secret": secret})
}

// testWebhook queues a webhook.test event for this webhook only. It is sent by
// the dispatcher like any other event, within seconds.
func (a *API) testWebhook(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	hook, err := a.Store.WebhookByID(r.Context(), id)
	if err != nil {
		a.fail(w, err)
		return
	}
	if !hook.Enabled {
		httpx.Error(w, http.StatusConflict, "this webhook is disabled; enable it to send a test")
		return
	}
	if !a.audit(w, r, "webhook.test", id, nil) {
		return
	}
	actor := ""
	if p := principal(r); p != nil {
		actor = p.User.Email
	}
	d, err := a.Store.AddWebhookEvent(r.Context(), id, webhook.Test, map[string]any{"webhook": hook.Name, "requestedBy": actor})
	if err != nil {
		a.fail(w, err)
		return
	}
	httpx.JSON(w, http.StatusAccepted, d)
}

func (a *API) listWebhookDeliveries(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	if _, err := a.Store.WebhookByID(r.Context(), id); err != nil {
		a.fail(w, err)
		return
	}
	before, _ := strconv.ParseInt(r.URL.Query().Get("before"), 10, 64)
	ds, err := a.Store.ListWebhookDeliveries(r.Context(), id, before, queryInt(r, "limit", 50))
	if err != nil {
		a.fail(w, err)
		return
	}
	httpx.JSON(w, http.StatusOK, map[string]any{"deliveries": nonNil(ds)})
}

func (a *API) retryWebhookDelivery(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	did, err := strconv.ParseInt(r.PathValue("deliveryId"), 10, 64)
	if err != nil {
		httpx.Error(w, http.StatusNotFound, "not found")
		return
	}
	if !a.audit(w, r, "webhook.retry", id, map[string]any{"delivery": did}) {
		return
	}
	if err := a.Store.RetryWebhookDelivery(r.Context(), id, did); err != nil {
		if errors.Is(err, store.ErrNotFound) {
			httpx.Error(w, http.StatusConflict, "this delivery does not exist, was already delivered, or is being sent right now")
			return
		}
		a.fail(w, err)
		return
	}
	w.WriteHeader(http.StatusNoContent)
}
